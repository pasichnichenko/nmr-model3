#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
NMR3-DRV92_calc.py — проверочные расчёты к справочной записке NMR3-DRV92
(LTC1992 / LTC1992-X как кандидат на место драйвера АЦП вместо LTC6362 + LT5400).

Все входные числа — из datasheet Linear Technology 1992fb (Rev B, 06/2011)
либо из уже принятых документов проекта (NMR3-DRV62, NMR3-ADC20, NMR3-OPA62).
Оцифровка графиков помечена в комментариях как [G##].

Запуск:  python3 NMR3-DRV92_calc.py
"""

import math

def db(x):            return 20.0 * math.log10(x)
def lin(x_db):        return 10.0 ** (x_db / 20.0)

L = []
def say(s=""):        L.append(s); print(s)

# ----------------------------------------------------------------------------
# 0. Исходные данные
# ----------------------------------------------------------------------------
F_IF      = 50e3          # ПЧ, Гц
FS        = 250e3         # частота выборки АЦП, Гц
F_NYQ     = FS / 2
VREF      = 5.0
FS_DIFF   = 2 * VREF      # полная шкала LTC2378-20, В_pp дифф.
V_WORK    = 8.0           # рабочий размах по NMR3-DRV62-P4, В_pp дифф.

# RC-фильтр драйвер -> АЦП (NMR3-DRV62 §3.3)
R_FILT, C_CM, C_DIFF = 125.0, 3900e-12, 3900e-12
F_C   = 1.0 / (2 * math.pi * R_FILT * (C_CM + 2 * C_DIFF))
BW_N  = 1.571 * F_C                      # шумовая полоса однополюсного ФНЧ

# АЦП
ADC_NOISE_RMS = 22.3e-6                  # из SNR = 104 дБ (NMR3-DRV62 §3.5)
ADC_DENS      = ADC_NOISE_RMS / math.sqrt(F_NYQ)

# LTC6362 (принятый вариант, NMR3-DRV62)
E_NO_6362   = 15.4e-9                    # выходная плотность при A_V = 2
SR_6362     = 45.0                       # В/мкс
PSRR_6362_50k = 90.0                     # дБ [график G14]
HD3_6362    = -84.0                      # dBc на 50 кГц, 8 В_pp

# LT6203 (ПЧ-каскад)
EN_6203 = 2.0e-9                         # нВ/√Гц на 50 кГц (допущение NMR3-OPA62)

# LTC1992-X: внутренние резисторы (Block Diagram, стр. 25)
FAMILY = {                               # part: (R_IN, R_FB)
    "LTC1992-1":  (30e3,  30e3),
    "LTC1992-2":  (30e3,  60e3),
    "LTC1992-5":  (30e3, 150e3),
    "LTC1992-10": (15e3, 150e3),
}
EN_AMP_X   = 45e-9     # нВ/√Гц @ 1 кГц, приведено ко входу усилителя, Note 7,
                       # тепловой шум внутренних резисторов УЖЕ включён (Figure 3)
EN_AMP_ADJ = 35e-9     # для нефиксированного LTC1992
SR_TYP, SR_MIN = 2.0, 0.7                # В/мкс, LTC1992-2/-5/-10 (у -1: 1.5/0.5)
CMRR_MIN, CMRR_TYP = 55.0, 60.0          # дБ, приведено ко входу усилителя (Note 7)
CMRR_G70_50k = 76.0                      # дБ [G70], типовой экземпляр на 50 кГц
PSRR_G73_50k = 32.0                      # дБ [G73] — оцифровка, ±2 дБ
GBW_2        = 4e6

say("=" * 78)
say("NMR3-DRV92 — проверочные расчёты (LTC1992 vs LTC6362 в узле драйвера АЦП)")
say("=" * 78)
say(f"ПЧ = {F_IF/1e3:.0f} кГц, f_s = {FS/1e3:.0f} kSps, полоса Найквиста = {F_NYQ/1e3:.0f} кГц")
say(f"RC-фильтр: f_c = {F_C/1e3:.2f} кГц, шумовая полоса = {BW_N/1e3:.1f} кГц")
say(f"Шум АЦП: {ADC_NOISE_RMS*1e6:.1f} мкВ_RMS -> {ADC_DENS*1e9:.1f} нВ/√Гц в полосе Найквиста")

# ----------------------------------------------------------------------------
# 1. Выходной шум каждой версии семейства
#    e_no = (1 + R_FB/R_IN) * e_n   (Figure 3, стр. 28)
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("1. Выходная плотность шума LTC1992-X (Figure 3)")
say("-" * 78)
say(f"{'часть':<12}{'G':>4}{'шум.усил.':>11}{'e_no, нВ/√Гц':>15}{'вход.имп. S-E, кОм':>21}")
noise = {}
for part, (rin, rfb) in FAMILY.items():
    G  = rfb / rin
    ng = 1 + rfb / rin
    e_no = ng * EN_AMP_X
    noise[part] = e_no
    r_se = rin / (1 - rfb / (2 * (rin + rfb)))      # стр. 30
    say(f"{part:<12}{G:>4.0f}{ng:>11.1f}{e_no*1e9:>15.1f}{r_se/1e3:>21.1f}")
E_NO_1992_2 = noise["LTC1992-2"]
say(f"\nLTC6362 при A_V = 2 (499/1k): {E_NO_6362*1e9:.1f} нВ/√Гц")
say(f"Проигрыш LTC1992-2: x{E_NO_1992_2/E_NO_6362:.1f} = {db(E_NO_1992_2/E_NO_6362):.1f} дБ")

# ----------------------------------------------------------------------------
# 2. Независимая проверка e_no по графику THD+N (G80) — шумовая полка
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("2. Сверка e_no с шумовыми полками графика G80 (полоса измерения 500 кГц)")
say("-" * 78)
BW_MEAS = 500e3
say(f"{'V_OUT, В_pp дифф':>18}{'полка [G80], дБ':>18}{'-> e_no, нВ/√Гц':>18}{'расчёт 135':>13}")
for vpp, plateau in [(1.0, -72.0), (2.0, -78.0), (5.0, -85.0), (10.0, -90.5)]:
    v_rms = vpp / (2 * math.sqrt(2))
    n_rms = v_rms * lin(plateau)
    dens  = n_rms / math.sqrt(BW_MEAS)
    say(f"{vpp:>18.0f}{plateau:>18.1f}{dens*1e9:>18.1f}{'✓' if abs(dens-E_NO_1992_2)/E_NO_1992_2 < 0.18 else '✗':>13}")
say("Вывод: полки графика воспроизводят паспортные 135 нВ/√Гц в пределах ±1 дБ чтения. [Р]")

# ----------------------------------------------------------------------------
# 3. Излом 1/f по графику G79
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("3. Реконструкция излома 1/f по G79 (e_n(f) = e_flat * sqrt(1 + f_c/f))")
say("-" * 78)
e_flat = 42e-9        # плато графика, приведено ко входу усилителя
pts = [(10.0, 300e-9), (100.0, 100e-9), (1e3, 55e-9)]
for f, e in pts:
    fc = f * ((e / e_flat) ** 2 - 1)
    say(f"  по точке {f:>6.0f} Гц / {e*1e9:>5.0f} нВ/√Гц  ->  f_c = {fc:>6.0f} Гц")
say("Принято: f_c ≈ 450…500 Гц -> на ПЧ 50 кГц надбавки за 1/f нет (как и у LTC6362). [Р]")

# ----------------------------------------------------------------------------
# 4. Сложенный шум и требуемое усиление ПЧ
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("4. Сложенный (aliased) шум на входе АЦП и требуемое усиление ПЧ-каскада")
say("-" * 78)
fold = math.sqrt(BW_N / F_NYQ)
say(f"Коэффициент складывания шумовой полосы в полосу Найквиста: {fold:.3f}")

def req_gain(e_no, gain_drv, degr_db, en_src=EN_6203):
    tot = math.hypot(ADC_DENS, e_no * fold)
    allowed = en_src * math.sqrt(lin(degr_db) ** 2 - 1)
    g = tot / (gain_drv * allowed)
    return tot, allowed, g

say(f"{'вариант':<26}{'сумм., нВ/√Гц':>15}{'G_IF @0.2 дБ':>14}{'G_IF @0.5 дБ':>14}")
for name, e_no in [("LTC6362 (A_V=2)", E_NO_6362), ("LTC1992-2", E_NO_1992_2)]:
    tot, _, g2 = req_gain(e_no, 2.0, 0.2)
    _,  _,  g5 = req_gain(e_no, 2.0, 0.5)
    say(f"{name:<26}{tot*1e9:>15.1f}{db(g2):>14.1f}{db(g5):>14.1f}")
tot6, _, g6 = req_gain(E_NO_6362, 2.0, 0.2)
tot9, _, g9 = req_gain(E_NO_1992_2, 2.0, 0.2)
say(f"\nДополнительное требование к ПЧ-каскаду: +{db(g9)-db(g6):.1f} дБ")
say("Нижняя ветвь NMR3-DRV62-O1 (43…49 дБ) формально ещё покрывает, но запас съедается. [Р]")

# ----------------------------------------------------------------------------
# 5. Скорость нарастания: требование против спецификации
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("5. Скорость нарастания на ПЧ 50 кГц (дифференциальная, как в Note 4)")
say("-" * 78)
say(f"{'размах, В_pp дифф':>18}{'треб. SR, В/мкс':>18}{'запас к тип. 2.0':>18}{'к гарант. 0.7':>16}")
for vpp in (4.0, 5.0, V_WORK, FS_DIFF):
    sr_req = 2 * math.pi * F_IF * (vpp / 2) / 1e6
    say(f"{vpp:>18.1f}{sr_req:>18.3f}{SR_TYP/sr_req:>18.2f}{SR_MIN/sr_req:>16.2f}")
fpbw_typ = SR_TYP * 1e6 / (2 * math.pi * (V_WORK / 2))
fpbw_min = SR_MIN * 1e6 / (2 * math.pi * (V_WORK / 2))
say(f"\nПолоса полной мощности при {V_WORK:.0f} В_pp: {fpbw_typ/1e3:.1f} кГц (тип.), "
    f"{fpbw_min/1e3:.1f} кГц (гарант.)")
say(f"ПЧ 50 кГц = {F_IF/fpbw_typ*100:.0f} % от типовой FPBW и "
    f"{F_IF/fpbw_min*100:.0f} % от гарантированной.")
sr_req_work = 2 * math.pi * F_IF * (V_WORK / 2) / 1e6
say(f"LTC6362: запас к {SR_6362:.0f} В/мкс = x{SR_6362/sr_req_work:.0f}")

# ----------------------------------------------------------------------------
# 6. Искажения и потолок накопления
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("6. Искажения на ПЧ и потолок накопления")
say("-" * 78)
THD_1992_8V = -53.0     # [G80/G81] при 8 В_pp дифф, 50 кГц
n_scans = 2000
gain_avg = 10 * math.log10(n_scans)
snr_single = 40.0
ceiling = snr_single + gain_avg
say(f"THD+N LTC1992-2 @ 8 В_pp, 50 кГц [G80/G81]: {THD_1992_8V:.0f} дБ")
say(f"HD3 LTC6362 @ 8 В_pp, 50 кГц (NMR3-DRV62):  {HD3_6362:.0f} dBc")
say(f"Разница: {abs(THD_1992_8V - HD3_6362):.0f} дБ в пользу LTC6362")
say(f"\nПотолок накопления {n_scans} сканов при одиночном SNR {snr_single:.0f} дБ: "
    f"{ceiling:.0f} дБ (+{gain_avg:.0f} дБ)")
say(f"  продукты LTC6362 ({HD3_6362:.0f} dBc): на {ceiling+HD3_6362:+.0f} дБ относительно пола -> ниже пола")
say(f"  продукты LTC1992-2 ({THD_1992_8V:.0f} dBc): на {ceiling+THD_1992_8V:+.0f} дБ -> ВЫШЕ пола")
say("Продукты когерентны от скана к скану — накоплением не подавляются. [Р]")

# Сверка с фирменным примером LT: LTC1992-1 + LTC1603, f_in = 10 кГц
say("\nСверка с фирменным примером LT (стр. 39): LTC1992-1 + LTC1603, 16 бит,")
say("  f_in = 10.0099 кГц, f_s = 333 кГц -> SNR = 85.3 дБ, THD = -72.1 дБ.")
say("  Уже на 10 кГц и 16-битном АЦП искажения ограничивают SINAD. [из datasheet]")

# ----------------------------------------------------------------------------
# 7. PSRR: спур от пульсации питания
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("7. Спур от пульсации питания на ПЧ (PSRR приведён ко входу усилителя, Note 7)")
say("-" * 78)
ng_2 = 1 + FAMILY["LTC1992-2"][1] / FAMILY["LTC1992-2"][0]
say(f"{'пульсация':>12}{'LTC1992-2 (PSRR 32 дБ)':>26}{'LTC6362 (PSRR 90 дБ)':>24}")
for ripple in (1e-3, 1e-4, 1e-5):
    s92 = ripple * lin(-PSRR_G73_50k) * ng_2
    s62 = ripple * lin(-PSRR_6362_50k) * 3
    say(f"{ripple*1e3:>9.3f} мВ{s92*1e6:>21.2f} мкВ{s62*1e6:>21.4f} мкВ")
say(f"\nШум АЦП для сравнения: {ADC_NOISE_RMS*1e6:.1f} мкВ_RMS.")
ripple_eq = ADC_NOISE_RMS * lin(-20) / (lin(-PSRR_G73_50k) * ng_2)
say(f"Чтобы спур был на 20 дБ ниже шума АЦП, пульсация на 50 кГц должна быть "
    f"< {ripple_eq*1e6:.1f} мкВ.")
say(f"Разрыв по PSRR на ПЧ: {PSRR_6362_50k - PSRR_G73_50k:.0f} дБ = "
    f"x{lin(PSRR_6362_50k - PSRR_G73_50k):.0f} по требуемой чистоте рельса. [Р]")

# ----------------------------------------------------------------------------
# 8. CMRR: приведение к единой системе отсчёта
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("8. CMRR: перевод паспортной цифры LTC1992-2 в конвенцию NMR3-DRV62")
say("-" * 78)
G = 2.0
say("Паспорт (Note 7) приведён ко входу усилителя. Цепочка пересчёта для G = 2:")
say(f"  V_AMPCM = G/(G+1)*V_INCM + 1/(G+1)*V_OCM  ->  коэффициент {G/(G+1):.4f}")
say(f"  ошибка на входе усилителя -> выход: шумовое усиление {1+G:.0f}")
say(f"  итого на выходе: V_INCM/CMRR * {G/(G+1)*(1+G):.2f}")
say(f"  приведение ко входу блока (делим на G = {G:.0f}): коэффициент {G/(G+1)*(1+G)/G:.2f}")
say("  => подавление, приведённое ко ВХОДУ блока, численно равно паспортному CMRR")
say(f"  => подавление, приведённое к ВЫХОДУ (конвенция NMR3-DRV62 §5): CMRR - {db(G):.0f} дБ")
say("")
say(f"{'вариант узла':<42}{'вых.-привед., дБ':>18}")
say(f"{'LTC1992-2, гарантированный минимум':<42}{CMRR_MIN - db(G):>18.1f}")
say(f"{'LTC1992-2, паспортный тип.':<42}{CMRR_TYP - db(G):>18.1f}")
say(f"{'LTC1992-2, типовой экземпляр @50 кГц [G70]':<42}{CMRR_G70_50k - db(G):>18.1f}")
say(f"{'LTC6362 + дискретные 0.1 %':<42}{54.0:>18.1f}")
say(f"{'LTC6362 + LT5400B (аттестовано, NMR3-LT54)':<42}{69.55:>18.1f}")
say("\nВывод: гарантированная цифра LTC1992-2 хуже узла с LT5400B на "
    f"{69.55 - (CMRR_MIN - db(G)):.1f} дБ и даже хуже дискретных 0.1 %. [Р]")

# ----------------------------------------------------------------------------
# 9. Чувствительность к несимметрии сопротивления источника
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("9. Несимметричное R_S источника: Δβ/β и эквивалентное CM->diff")
say("-" * 78)
def dbeta(rin, rfb, rs):
    b1 = (rin + rs) / (rin + rs + rfb)
    b2 = rin / (rin + rfb)
    return abs(b2 - b1) / ((b1 + b2) / 2)

say(f"{'R_S, Ом':>9}{'LTC6362 (499/1k)':>22}{'LTC1992-2 (30k/60k)':>24}")
for rs in (1.0, 5.0, 50.0):
    d62 = dbeta(499.0, 1000.0, rs)
    d92 = dbeta(30e3, 60e3, rs)
    say(f"{rs:>9.0f}{db(d62):>19.1f} дБ{db(d92):>21.1f} дБ")
say("\nЗдесь LTC1992-2 объективно лучше: R_IN в 60 раз больше, поэтому тот же")
say("паразитный резистор в плече даёт на ~36 дБ меньшую разбалансировку. [Р]")
say("Но у LTC1992-X резисторы внутри — продублировать R_S во втором плече НЕЛЬЗЯ")
say("(требование NMR3-DRV62-P3 нечем выполнить), так что эта стойкость вынужденная.")

# ----------------------------------------------------------------------------
# 10. Смещение от сдвига уровня
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("10. Смещение выхода от сдвига уровня (стр. 30 + Figure 6)")
say("-" * 78)
for mism in (1e-3, 5e-4, 1e-4):
    for shift in (1.25, 2.5):
        say(f"  рассогласование {mism*100:.2f} %, сдвиг {shift:.2f} В -> "
            f"{2*shift*mism*1e3:.2f} мВ на выходе "
            f"({2*shift*mism/ (FS_DIFF/2**20):.0f} LSB 20-бит)")
say("DC, при low-IF лежит вне полосы, снимается калибровкой. Не блокирует. [Р]")

# ----------------------------------------------------------------------------
# 11. Полоса и ёмкостная нагрузка
# ----------------------------------------------------------------------------
say("\n" + "-" * 78)
say("11. Полоса замкнутой петли и ёмкостная нагрузка")
say("-" * 78)
say(f"LTC1992-2: GBW = {GBW_2/1e6:.0f} МГц / шумовое усиление {ng_2:.0f} = "
    f"{GBW_2/ng_2/1e6:.2f} МГц -> x{GBW_2/ng_2/F_IF:.0f} к ПЧ. Достаточно.")
say("C_LOAD: устойчив до 10 000 пФ по спецификации -> RC 3900 пФ безопасен,")
say("горба АЧХ, требующего запрета NMR3-DRV62-P5, у этого семейства нет.")

say("\n" + "=" * 78)
say("ИТОГ: по четырём независимым критериям (PSRR на ПЧ, искажения на ПЧ,")
say("шум, гарантированный CMRR) LTC1992-2 уступает узлу LTC6362 + LT5400B.")
say("Единственные его преимущества — высокий входной импеданс и устойчивость")
say("к несимметрии источника — не окупают ни одного из четырёх проигрышей.")
say("=" * 78)

if __name__ == "__main__":
    pass
