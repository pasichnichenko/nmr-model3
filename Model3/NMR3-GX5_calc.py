hr("9. Свёртка гармоник (гипотеза к рис. 16) и пример для NMR3")
def fold(f, fs):
    return abs(f - fs * round(f / fs))
f0, fs = 10.8, 75.0
for kk in range(2, 21):
    a = fold(kk * f0, fs)
    off = a - f0
    mark = "  <==" if abs(abs(off) - 0.6) < 0.05 or abs(abs(off) - 1.2) < 0.05 else ""
    if abs(off) < 2.0:
        print(f"k={kk:2d}: {kk*f0:6.1f} МГц → {a:6.2f} МГц, смещение {off*1e3:+7.0f} кГц{mark}")
